/**
 * Universal text translation function.
 * If language is Urdu ("ur"), accurately converts known English terms,
 * phrases, crops, and agronomic indicators into natural Pakistani agricultural Urdu.
 */
export function translateTextToUrdu(text: string | undefined | null): string {
  if (!text) return "";
  const trimmed = String(text).trim();
  
  // Exact match
  if (AGRICULTURAL_DICTIONARY[trimmed]) {
    return AGRICULTURAL_DICTIONARY[trimmed];
  }

  // Case-insensitive match
  const lower = trimmed.toLowerCase();
  for (const [key, val] of Object.entries(AGRICULTURAL_DICTIONARY)) {
    if (key.toLowerCase() === lower) {
      return val;
    }
  }

  // Common compound patterns
  if (trimmed.startsWith("Elevated Disease Risk: ")) {
    const disease = trimmed.replace("Elevated Disease Risk: ", "");
    return `بیماری کا بڑھتا ہوا خطرہ: ${translateTextToUrdu(disease)}`;
  }

  if (trimmed.startsWith("Irrigation Required: ")) {
    const cropPart = trimmed.replace("Irrigation Required: ", "");
    return `آبپاشی کی ضرورت: ${cropPart}`;
  }

  if (trimmed.endsWith(" Growth Phases")) {
    const cropName = trimmed.replace(" Growth Phases", "");
    return `${translateTextToUrdu(cropName)} کے نشوونما کے مراحل`;
  }

  if (trimmed.startsWith("Total ") && trimmed.endsWith(" days")) {
    const daysPart = trimmed.replace("Total ", "").replace(" days", "");
    return `کل دورانیہ: ${daysPart} دن`;
  }

  if (trimmed.startsWith("Direction: ")) {
    return trimmed.replace("Direction: ", "ہوا کا رخ: ");
  }

  if (trimmed.startsWith("Spray Quality: ")) {
    const q = trimmed.replace("Spray Quality: ", "");
    return `اسپرے کا معیار: ${translateTextToUrdu(q)}`;
  }

  if (trimmed.startsWith("Quality: ")) {
    const q = trimmed.replace("Quality: ", "");
    return `معیار: ${translateTextToUrdu(q)}`;
  }

  if (trimmed.startsWith("Possible condition: ")) {
    const c = trimmed.replace("Possible condition: ", "");
    return `ممکنہ بیماری: ${translateTextToUrdu(c)}`;
  }

  return trimmed;
}
